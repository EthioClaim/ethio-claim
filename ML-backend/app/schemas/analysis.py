from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from datetime import datetime


# ==========================================
# Input Request Schemas
# ==========================================

class ExactMatchInput(BaseModel):
    evidenceId: str
    claimId: Optional[str] = None


class PerceptualMatchInput(BaseModel):
    evidenceId: str
    claimId: Optional[str] = None
    distance: int = 0


class HashMatchesInput(BaseModel):
    exactMatches: List[ExactMatchInput] = Field(default_factory=list)
    perceptualMatches: List[PerceptualMatchInput] = Field(default_factory=list)


class AnalysisOptions(BaseModel):
    damageDetection: bool = True
    embeddingSimilarity: bool = True
    ocrExtraction: bool = False
    topK: int = 5


class AnalysisRequest(BaseModel):
    analysisId: str = Field(..., description="UUID of DamageAnalysis record generated by NestJS")
    evidenceId: str = Field(..., description="UUID of Evidence record")
    claimId: str = Field(..., description="UUID of Claim record")
    tenantId: Optional[str] = Field("default", description="Tenant or Insurer identifier for multi-tenant isolation")
    imageRef: Optional[str] = Field(None, description="Trusted internal storage key or relative path")
    imageUrl: Optional[str] = Field(None, description="Short-lived signed URL or local endpoint to fetch image")
    imageBase64: Optional[str] = Field(None, description="Base64 encoded image string (optional fallback or testing)")
    sha256: Optional[str] = Field(None, description="Precomputed SHA-256 hash provided by NestJS")
    phash: Optional[str] = Field(None, description="Precomputed perceptual hash provided by NestJS")
    hashMatches: Optional[HashMatchesInput] = Field(default_factory=HashMatchesInput)
    options: Optional[AnalysisOptions] = Field(default_factory=AnalysisOptions)


# ==========================================
# Output Response Schemas
# ==========================================

class DamageDetection(BaseModel):
    label: str = Field(..., description="Type of damage detected, e.g. front_bumper_dent, scratch, headlight_crack")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Detection confidence score between 0.0 and 1.0")
    severity: str = Field("MODERATE", description="Severity category: MINOR, MODERATE, SEVERE, or UNDETERMINED")
    box: List[float] = Field(..., min_length=4, max_length=4, description="Normalized coordinates [ymin, xmin, ymax, xmax]")
    areaPercentage: Optional[float] = Field(None, description="Percentage of total image area occupied by damage")


class EmbeddingResult(BaseModel):
    stored: bool = Field(..., description="Whether vector embedding was successfully stored in vector database")
    pointId: Optional[str] = Field(None, description="Stable Qdrant point UUID associated with evidence")
    model: str = Field(..., description="Vision encoder model name")
    version: str = Field(..., description="Model version tag")
    dimension: Optional[int] = Field(None, description="Embedding vector length")


class VisualMatch(BaseModel):
    evidenceId: str = Field(..., description="Historical evidence record UUID")
    claimId: Optional[str] = Field(None, description="Historical claim record UUID")
    similarity: float = Field(..., ge=0.0, le=1.0, description="Cosine similarity score (0.0 to 1.0)")


class RiskAssessment(BaseModel):
    label: str = Field(
        ...,
        description="Screening risk label: POTENTIAL_FRAUD, NO_FRAUD_INDICATORS_FOUND, INCONCLUSIVE, or ANALYSIS_FAILED",
    )
    score: Optional[float] = Field(None, description="Calibrated risk probability or null for rules-based MVP")
    reasons: List[str] = Field(default_factory=list, description="Explicit bulleted rationales for the assigned risk label")
    requiresExaminerReview: bool = Field(..., description="Mandatory flag indicating if manual examiner assessment is required")
    ruleVersion: str = Field(..., description="Version of the risk screening rules applied")


class OcrField(BaseModel):
    value: str
    confidence: float


class OcrResult(BaseModel):
    detectedText: Optional[str] = None
    documentType: Optional[str] = None
    extractedFields: Dict[str, Any] = Field(default_factory=dict)


class AnalysisResponse(BaseModel):
    analysisId: str
    evidenceId: str
    claimId: Optional[str] = None
    status: str = Field(..., description="COMPLETED, FAILED, or INCONCLUSIVE")
    damageDetections: List[DamageDetection] = Field(default_factory=list)
    embedding: EmbeddingResult
    visualMatches: List[VisualMatch] = Field(default_factory=list)
    riskAssessment: RiskAssessment
    ocrResult: Optional[OcrResult] = None
    warnings: List[str] = Field(default_factory=list)
    createdAt: str = Field(default_factory=lambda: datetime.utcnow().isoformat() + "Z")
    errorCode: Optional[str] = None
    errorMessage: Optional[str] = None
